-- Questmaster core schema

CREATE EXTENSION IF NOT EXISTS unaccent;

-- Slugs: lowercase, accents removed, runs of characters other than ASCII letters and digits
-- become a hyphen. Names without any of them fall back to the entity type ("campaign",
-- "character"). A numeric suffix keeps them unique; the loop skips the row itself, so
-- regenerating a slug for an unchanged base keeps it.

CREATE OR REPLACE FUNCTION public.generate_unique_campaign_slug()
    RETURNS trigger
    LANGUAGE plpgsql
AS $BODY$
DECLARE
  base_slug TEXT;
  new_slug TEXT;
  counter INTEGER := 1;
BEGIN
  base_slug := trim(both '-' from regexp_replace(unaccent(lower(NEW.name)), '[^a-z0-9]+', '-', 'g'));
  IF base_slug = '' THEN
    base_slug := 'campaign';
  END IF;

  new_slug := base_slug;
  WHILE EXISTS (SELECT 1 FROM campaign WHERE slug = new_slug AND id <> NEW.id) LOOP
    counter := counter + 1;
    new_slug := base_slug || '-' || counter::TEXT;
  END LOOP;

  NEW.slug := new_slug;
  RETURN NEW;
END;
$BODY$;

CREATE OR REPLACE FUNCTION public.generate_unique_character_sheet_slug()
    RETURNS trigger
    LANGUAGE plpgsql
AS $BODY$
DECLARE
  base_slug TEXT;
  new_slug TEXT;
  counter INTEGER := 1;
BEGIN
  base_slug := trim(both '-' from regexp_replace(unaccent(lower(NEW.name)), '[^a-z0-9]+', '-', 'g'));
  IF base_slug = '' THEN
    base_slug := 'character';
  END IF;

  new_slug := base_slug;
  WHILE EXISTS (SELECT 1 FROM character_sheet WHERE slug = new_slug AND id <> NEW.id) LOOP
    counter := counter + 1;
    new_slug := base_slug || '-' || counter::TEXT;
  END LOOP;

  NEW.slug := new_slug;
  RETURN NEW;
END;
$BODY$;

CREATE TABLE public.campaign
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(255) NOT NULL,
    dm_id uuid NOT NULL,
    -- How the DM is called in this campaign, given when creating it
    dm_name character varying(50) NOT NULL,
    status character varying(45) NOT NULL DEFAULT 'DRAFT',
    game_system character varying(45) NOT NULL,
    slug character varying(255) NOT NULL CONSTRAINT campaign_slug_key UNIQUE,
    overview text
);

CREATE INDEX campaign_dm_id_idx ON public.campaign (dm_id);

CREATE TRIGGER trg_generate_slug
BEFORE INSERT ON public.campaign
FOR EACH ROW EXECUTE FUNCTION public.generate_unique_campaign_slug();

-- A character without a player is a premade character prepared by its campaign DM.
-- Deleting a campaign unlinks its characters; the application deletes unclaimed premade ones first.
CREATE TABLE public.character_sheet
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(255) NOT NULL,
    player_id uuid,
    -- How the player is called in the character's campaign; set when joining, cleared when leaving
    player_name character varying(50),
    campaign_id bigint REFERENCES public.campaign (id) ON DELETE SET NULL,
    game_system character varying(45) NOT NULL,
    slug character varying(255) NOT NULL CONSTRAINT character_sheet_slug_key UNIQUE
);

CREATE INDEX character_sheet_player_id_idx ON public.character_sheet (player_id);
CREATE INDEX character_sheet_campaign_id_idx ON public.character_sheet (campaign_id);

CREATE TRIGGER trg_generate_slug
BEFORE INSERT ON public.character_sheet
FOR EACH ROW EXECUTE FUNCTION public.generate_unique_character_sheet_slug();

-- Renaming regenerates the slug, only when the name actually changes
CREATE TRIGGER trg_regenerate_slug_on_rename
BEFORE UPDATE OF name ON public.character_sheet
FOR EACH ROW
WHEN (OLD.name IS DISTINCT FROM NEW.name)
EXECUTE FUNCTION public.generate_unique_character_sheet_slug();

CREATE TABLE public.campaign_invite
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint NOT NULL CONSTRAINT campaign_invite_campaign_id_key UNIQUE
        REFERENCES public.campaign (id) ON DELETE CASCADE,
    hash uuid NOT NULL DEFAULT gen_random_uuid() CONSTRAINT campaign_invite_hash_key UNIQUE
);

-- Last time each user opened a campaign or one of their characters, for the "recent" list sort
CREATE TABLE public.campaign_access
(
    user_id uuid NOT NULL,
    campaign_id bigint NOT NULL REFERENCES public.campaign (id) ON DELETE CASCADE,
    accessed_at timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, campaign_id)
);

CREATE TABLE public.character_access
(
    user_id uuid NOT NULL,
    character_id bigint NOT NULL REFERENCES public.character_sheet (id) ON DELETE CASCADE,
    accessed_at timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, character_id)
);
